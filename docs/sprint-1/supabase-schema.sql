-- Esquema PostgreSQL equivalente a las tablas definidas actualmente en backend/db.js.
-- Ejecutar manualmente en el SQL Editor del proyecto Supabase después de revisar.

CREATE TABLE public.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  is_demo boolean DEFAULT false,
  daily_hours_limit real DEFAULT 6,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE public.events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  event_type text NOT NULL DEFAULT '',
  event_date text NOT NULL DEFAULT '',
  course text NOT NULL DEFAULT '',
  weight numeric(5,2),
  description text DEFAULT '',
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.tasks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id integer NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  title text NOT NULL,
  description text DEFAULT '',
  scheduled_date text,
  estimated_hours real DEFAULT 1,
  status text DEFAULT 'pending' CHECK (status IN ('pending', 'done', 'postponed')),
  note text DEFAULT '',
  created_at timestamptz DEFAULT now()
);

CREATE TABLE public.task_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id integer NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  action text NOT NULL,
  note text DEFAULT '',
  prev_date text,
  new_date text,
  prev_hours real,
  new_hours real,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE public.password_reset_tokens (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_tasks_user_status ON public.tasks(user_id, status);
CREATE INDEX idx_tasks_user_date ON public.tasks(user_id, scheduled_date);
CREATE INDEX idx_password_reset_tokens_user ON public.password_reset_tokens(user_id, expires_at DESC);
